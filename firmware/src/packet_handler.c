uint8_t crc8_smbus(const uint8_t *data, size_t len) {
    uint8_t crc = 0x00;
    for (size_t i = 0; i < len; i++) {
        crc = crc8_table[crc ^ data[i]];
    }
    return crc;
}

uint32_t get_last_packet_time_us(void) {
    return s_last_packet_time;
}

void packet_handler_init(void) {
    s_last_packet_time = time_us_32();
    memset(&s_current_report, 0, sizeof(s_current_report));
    s_current_report.report_id  = 0x00;
    s_current_report.report_len = 0x14;
}

// CPT Compliant Neutral SOCD (Up+Down -> N, Left+Right -> N)
static inline uint8_t socd_clean(uint8_t d) {
    if ((d & 0x03) == 0x03) d &= ~0x03; // Up + Down -> Neutral
    if ((d & 0x0C) == 0x0C) d &= ~0x0C; // Left + Right -> Neutral
    return d;
}

static void unpack_to_xinput(const uint8_t *rx_buf, xinput_report_t *rep) {
    memset(rep, 0, sizeof(xinput_report_t));
    rep->report_id  = 0x00;
    rep->report_len = 0x14;

    // 1. D-Pad & System Buttons (Byte 1)
    uint8_t dpad = socd_clean(rx_buf[1] & 0x0F);
    rep->buttons |= (dpad & 0x0F);                  // bit0-3: UP, DOWN, LEFT, RIGHT
    if (rx_buf[1] & 0x10) rep->buttons |= 0x0010;   // Start
    if (rx_buf[1] & 0x20) rep->buttons |= 0x0020;   // Back
    if (rx_buf[1] & 0x40) rep->buttons |= 0x0400;   // Guide (Xbox button)

    // 2. Action Buttons (Byte 2)
    if (rx_buf[2] & 0x01) rep->buttons |= 0x1000;   // A
    if (rx_buf[2] & 0x02) rep->buttons |= 0x2000;   // B
    if (rx_buf[2] & 0x04) rep->buttons |= 0x4000;   // X
    if (rx_buf[2] & 0x08) rep->buttons |= 0x8000;   // Y
    if (rx_buf[2] & 0x10) rep->buttons |= 0x0100;   // LB
    if (rx_buf[2] & 0x20) rep->buttons |= 0x0200;   // RB
    if (rx_buf[2] & 0x40) rep->buttons |= 0x0040;   // L3 (Left Thumb)
    if (rx_buf[2] & 0x80) rep->buttons |= 0x0080;   // R3 (Right Thumb)

    // 3. Left Stick XY Axes (Byte 3 Lower 4bit) - Square Digital (+-32767)
    uint8_t ls = socd_clean(rx_buf[3] & 0x0F);
    rep->lx = (ls & 0x04) ? -32768 : ((ls & 0x08) ? 32767 : 0);
    rep->ly = (ls & 0x02) ? -32768 : ((ls & 0x01) ? 32767 : 0); // Up is positive, Down is negative

    // Cross-system SOCD: Neutralize opposing inputs between D-Pad and Left Stick
    if (((dpad & 0x04) && rep->lx > 0) || ((dpad & 0x08) && rep->lx < 0)) {
        rep->buttons &= ~0x000C;
        rep->lx = 0;
    }
    if (((dpad & 0x01) && rep->ly < 0) || ((dpad & 0x02) && rep->ly > 0)) {
        rep->buttons &= ~0x0003;
        rep->ly = 0;
    }

    // 4. Right Stick XY Axes (Byte 3 Upper 4bit) - Square Digital (+-32767)
    uint8_t rs = socd_clean((rx_buf[3] >> 4) & 0x0F);
    rep->rx = (rs & 0x04) ? -32768 : ((rs & 0x08) ? 32767 : 0);
    rep->ry = (rs & 0x02) ? -32768 : ((rs & 0x01) ? 32767 : 0);

    // 5. Trigger expansion (Byte 4)
    rep->lt = (rx_buf[4] >> 4) * 17;
    rep->rt = (rx_buf[4] & 0x0F) * 17;

    // Record reception timestamp
    s_last_packet_time = time_us_32();
}

void handle_received_packet(const uint8_t *rx_buf) {
    // CRC-8 validation over first 5 bytes
    if (crc8_smbus(rx_buf, 5) != rx_buf[5]) {
        return; // CRC mismatch: reject corrupt packet
    }

    // 1. Normal Input Packet (0x5A)
    if (rx_buf[0] == 0x5A) {
        // Crash prevention guard:
        // In MODE_A, XInput endpoints are not active. Discard 0x5A packets completely to prevent hard faults.
        if (get_current_operating_mode() != MODE_B) {
            return;
        }

        unpack_to_xinput(rx_buf, &s_current_report);
        xinput_send_report((const uint8_t *)&s_current_report, sizeof(s_current_report));
    }
    // 2. Special Control Command (0xA5)
    else if (rx_buf[0] == 0xA5) {
        uint8_t cmd_id = rx_buf[1];
        uint8_t check  = rx_buf[2];

        // Inverse bit check: ~cmd_id == check
        if ((uint8_t)(~cmd_id) == check) {
            if (cmd_id == 0x01) {
                reboot_to_mode(MODE_B); // Start Game Mode (PID 0x000B)
            } else if (cmd_id == 0x02) {
                reboot_to_mode(MODE_A); // Revert to Normal Mode (PID 0x000A)
            } else if (cmd_id == 0x03) {
                // Logical P1 Reset: re-enumerate maintaining current mode
                reboot_to_mode(get_current_operating_mode());
            }
        }
    }
}

